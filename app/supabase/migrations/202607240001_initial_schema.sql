-- This is the future public-only boundary. The app currently reads the base tables so
-- unverified sample rows remain visible. Switching the repository to this view exposes
-- only university rows whose owning source has been verified.
create view public.verified_universities
with (security_invoker = true)
as
select u.*
from public.universities u
join public.sources s on s.id = u.source_id
where s.verification = 'verified';

grant select on public.verified_universities to anon, authenticated;

comment on table public.university_facts is
  'Known facts require source_id; unknown facts require a reason and suggested action.';
comment on view public.verified_universities is
  'Stable public-read boundary for the later verified-only launch mode.';
