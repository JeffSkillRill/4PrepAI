alter type public.university_fact_kind add value if not exists 'employability_summary';
alter type public.university_fact_kind add value if not exists 'faculty_count';

create table public.rankings (
  id bigint generated by default as identity primary key,
  university_id text not null references public.universities(id) on delete cascade,
  label text not null,
  rank_display text not null,
  year integer,
  source_id text not null references public.sources(id)
);

create table public.campuses (
  id bigint generated by default as identity primary key,
  university_id text not null references public.universities(id) on delete cascade,
  name text not null,
  city text not null,
  country text not null,
  source_id text not null references public.sources(id)
);

create index rankings_university_id_idx on public.rankings (university_id);
create index rankings_source_id_idx on public.rankings (source_id);
create index campuses_university_id_idx on public.campuses (university_id);
create index campuses_source_id_idx on public.campuses (source_id);

alter table public.rankings enable row level security;
alter table public.campuses enable row level security;
create policy "read rankings" on public.rankings for select to anon, authenticated using (true);
create policy "read campuses" on public.campuses for select to anon, authenticated using (true);
grant select on public.rankings, public.campuses to anon, authenticated;

