-- Generic, sourced profile data. These labels deliberately contain no provider
-- name: a future QS import is only one possible verified source.
create type public.program_degree_level as enum ('bachelor', 'master', 'mba', 'phd');
create type public.program_subject_area as enum (
  'Arts and Humanities', 'Business and Management', 'Engineering and Technology',
  'Life Sciences and Medicine', 'Natural Sciences', 'Social Sciences and Management'
);

alter table public.programs
  add column degree_level public.program_degree_level,
  add column subject_area public.program_subject_area;

update public.programs
set degree_level = case
  when lower(degree) ~ '(master|m\.s\.|m\.a\.|msc|meng)' then 'master'::public.program_degree_level
  when lower(degree) ~ '(mba|master of business)' then 'mba'::public.program_degree_level
  when lower(degree) ~ '(ph\.d|doctor)' then 'phd'::public.program_degree_level
  else 'bachelor'::public.program_degree_level
end,
subject_area = case
  when field ilike '%business%' or field ilike '%management%' then 'Business and Management'::public.program_subject_area
  when field ilike '%humanit%' or field ilike '%art%' then 'Arts and Humanities'::public.program_subject_area
  when field ilike '%life science%' or field ilike '%medicine%' then 'Life Sciences and Medicine'::public.program_subject_area
  when field ilike '%natural science%' then 'Natural Sciences'::public.program_subject_area
  when field ilike '%social science%' then 'Social Sciences and Management'::public.program_subject_area
  else 'Engineering and Technology'::public.program_subject_area
end;

alter table public.programs
  alter column degree_level set not null,
  alter column subject_area set not null;

alter type public.university_fact_kind add value if not exists 'international_student_pct';
